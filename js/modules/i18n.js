class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('photo_lang') || 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindLanguageToggles();
  }

  t(key, fallback = '') {
    const langDict = translations[this.currentLang] || translations.en;
    return langDict[key] || translations.en[key] || fallback || key;
  }

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'hi') lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('photo_lang', lang);
    this.applyLanguage(lang);
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  toggleLanguage() {
    this.setLanguage(this.currentLang === 'en' ? 'hi' : 'en');
  }

  applyLanguage(lang) {
    document.documentElement.setAttribute('lang', lang);

    // Update all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val) {
        // If element has nested icon, update only the text node if possible, or el.innerHTML
        if (el.querySelector('i, svg')) {
          const icon = el.querySelector('i, svg').outerHTML;
          el.innerHTML = icon + ' ' + val;
        } else {
          el.textContent = val;
        }
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val) el.setAttribute('placeholder', val);
    });

    // Update titles / tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val) el.setAttribute('title', val);
    });

    // Update language toggle buttons text/label
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      const isHindi = lang === 'hi';
      btn.innerHTML = isHindi 
        ? '<span style="font-size:1.1rem">🌐</span> <span>English</span>' 
        : '<span style="font-size:1.1rem">🇮🇳</span> <span>हिंदी</span>';
      btn.setAttribute('title', isHindi ? 'Switch to English' : 'हिंदी में बदलें');
    });
  }

  bindLanguageToggles() {
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        this.toggleLanguage();
      });
    });
  }
}

// Global instance
window.i18n = new I18nManager();
document.addEventListener('DOMContentLoaded', () => {
  window.i18n.init();

  // Universal Mobile Sidebar Handler across all tools
  const btnToggle = document.getElementById('btnToggleSidebar');
  const btnClose = document.getElementById('btnCloseSidebar');
  const sidebar = document.getElementById('appSidebar');
  const backdrop = document.getElementById('sidebarBackdrop');

  function closeSidebar() {
    if (sidebar) sidebar.classList.remove('drawer-open');
    if (backdrop) backdrop.classList.remove('active');
    document.body.style.overflow = '';
  }

  function openSidebar() {
    if (sidebar) sidebar.classList.add('drawer-open');
    if (backdrop) backdrop.classList.add('active');
    if (window.innerWidth <= 900) {
      document.body.style.overflow = 'hidden';
    }
  }

  if (btnToggle && sidebar) {
    btnToggle.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      if (sidebar.classList.contains('drawer-open')) closeSidebar();
      else openSidebar();
    });
  }

  if (btnClose) {
    btnClose.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      closeSidebar();
    });
  }

  if (backdrop) {
    backdrop.addEventListener('click', closeSidebar);
  }

  document.querySelectorAll('.sidebar-nav-item').forEach(item => {
    item.addEventListener('click', () => {
      if (window.innerWidth <= 900) closeSidebar();
    });
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeSidebar();
  });
});
